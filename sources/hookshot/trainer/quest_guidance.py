def generate_quest_guidance(rom, output, regions=None):
    challenges = rom.byml("RSDB/Challenge.Product.111.rstbl.byml.zs")
    enums = rom.byml(GAME_DATA)["Data"]["Enum"]
    lines = ["/* Generated from the installed game's challenge and enum tables. */"]
    if regions is not None:
        from world_map import STAGE_GOALS
        if len(STAGE_GOALS) != len(QUESTS):
            raise ValueError("Missing quest map destinations")
    quest_rows = []
    for index, (name, title, groups) in enumerate(QUESTS):
        challenge, = (row for row in challenges if row["__RowId"].split("/")[-1].split(".")[0] == name)
        stages = ["NotReady", *(step["Name"] for step in challenge["Steps"]), "Complete"]
        entry, = (row for row in enums if row["RawValues"] == stages and row["SaveFileIndex"] == 0)
        hints = [hint for count, *hint in groups for _ in range(count)]
        hints.append(["", "", ""])
        if len(hints) != len(stages) or len(entry["Values"]) != len(stages):
            raise ValueError(f"{name}: quest steps and hints have different lengths")
        goals = [0] * len(stages)
        if regions is not None:
            group_goals = STAGE_GOALS[name].split()
            if len(group_goals) != len(groups):
                raise ValueError(f"{name}: map destinations and hint groups have different lengths")
            goals = [regions[goal] for (count, *_), goal in zip(groups, group_goals) for _ in range(count)] + [0]
        lines.append(f"static const HkQuestStep hk_quest_steps_{index}[] = {{")
        for value, stage, hint, goal in zip(entry["Values"], stages, hints, goals):
            strings = ", ".join("L" + json.dumps(s, ensure_ascii=False) for s in hint)
            lines.append(f"    {{ 0x{value:08x}u, {strings}, {goal} }}, /* {stage} */")
        lines.append("};")
        quest_rows.append(f'    {{ 0x{entry["Hash"]:08x}u, L"{title}", hk_quest_steps_{index}, {len(stages)} }}, /* {name} */')
    lines.extend(("static const HkQuestDefinition hk_quests[] = {", *quest_rows, "};"))
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
